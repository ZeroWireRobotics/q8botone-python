'''
Written by yufeng.wu0902@gmail.com

Exports a gait's precomputed trajectory tables (all 12 direction variants)
from gait_manager.py into a generated C++ header for the robot firmware,
so that gait can run autonomously on-device via the GAIT_RUN command
(see protocol.py) instead of being streamed frame-by-frame from the host.

Re-run this whenever the exported gait's parameters in gait_manager.py's
GAITS dict change, then rebuild/reflash q8bot_robot.

Usage:
    python export_gait_tables.py
'''

import os

from kinematics_solver import k_solver
from gait_manager import GaitManager, GAITS
from protocol import DIRECTION_ORDER, GAIT_IDS

# Q8bot leg configuration (must match operate.py)
CENTER_DIST = 19.5
L1 = 25
L2 = 40

OUTPUT_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..", "..", "firmware", "q8bot_robot", "include", "gaitTables.h"
)


def sanitize(direction):
    """Turn a direction key like 'fl_0.75' into a valid C identifier suffix."""
    return direction.upper().replace('.', '_')


def format_frame_array(name, frames):
    lines = [f"static const GaitFrame {name}[{len(frames)}] = {{"]
    for frame in frames:
        values = ", ".join(f"{v:.4f}f" for v in frame)
        lines.append(f"  {{{{{values}}}}},")
    lines.append("};")
    return "\n".join(lines)


def export_gait(gait_id, gait_name):
    leg = k_solver(CENTER_DIST, L1, L2, L1, L2)
    gm = GaitManager(leg, GAITS)

    if not gm.load_gait(gait_name):
        raise RuntimeError(f"Failed to generate trajectories for {gait_name}")

    trajectories = gm.current_trajectories[gait_name]

    missing = [d for d in DIRECTION_ORDER if d not in trajectories]
    if missing:
        raise RuntimeError(f"{gait_name} is missing direction(s): {missing}")

    array_names = []
    frame_arrays = []
    counts = []
    for direction in DIRECTION_ORDER:
        frames = trajectories[direction]
        array_name = f"{gait_name}_{sanitize(direction)}"
        array_names.append(array_name)
        counts.append(len(frames))
        frame_arrays.append(format_frame_array(array_name, frames))

    directions_table_name = f"{gait_name}_DIRECTIONS"
    directions_entries = ",\n".join(
        f"  {{{name}, {count}}}" for name, count in zip(array_names, counts)
    )

    return frame_arrays, directions_table_name, directions_entries


def main():
    header_lines = [
        "#pragma once",
        "// AUTO-GENERATED by python-tools/q8bot/export_gait_tables.py",
        "// DO NOT HAND-EDIT - re-run the export script instead.",
        "//",
        "// Direction order (must match protocol.py's DIRECTION_ORDER):",
        "// " + ", ".join(f"{d}={i}" for i, d in enumerate(DIRECTION_ORDER)),
        "",
        "#include <Arduino.h>",
        "",
        "struct GaitFrame { float degs[8]; };",
        "struct GaitDirectionTable { const GaitFrame* frames; uint16_t count; };",
        "",
    ]

    gait_table_entries = []

    for gait_id, gait_name in GAIT_IDS.items():
        frame_arrays, directions_table_name, directions_entries = export_gait(gait_id, gait_name)

        header_lines.extend(frame_arrays)
        header_lines.append("")
        header_lines.append(f"static const GaitDirectionTable {directions_table_name}[12] = {{")
        header_lines.append(directions_entries)
        header_lines.append("};")
        header_lines.append("")

        gait_table_entries.append((gait_id, directions_table_name))

    max_gait_id = max(gait_table_entries, key=lambda e: e[0])[0]
    gait_tables = ["nullptr"] * (max_gait_id + 1)
    for gait_id, directions_table_name in gait_table_entries:
        gait_tables[gait_id] = directions_table_name

    header_lines.append(f"static const GaitDirectionTable* GAIT_TABLES[{len(gait_tables)}] = {{")
    header_lines.append("  " + ", ".join(gait_tables))
    header_lines.append("};")
    header_lines.append(f"static const uint8_t GAIT_TABLE_COUNT = {len(gait_tables)};")
    header_lines.append("")

    output_path = os.path.normpath(OUTPUT_PATH)
    with open(output_path, "w") as f:
        f.write("\n".join(header_lines))

    print(f"Wrote {output_path}")
    for gait_id, gait_name in GAIT_IDS.items():
        print(f"  gait_id={gait_id} -> {gait_name}")


if __name__ == "__main__":
    main()
